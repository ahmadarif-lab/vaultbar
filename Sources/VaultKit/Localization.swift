import Foundation

public enum Language: String, CaseIterable, Sendable, Identifiable {
    case en, id
    public var id: String { rawValue }
    public var displayName: String { self == .en ? "English" : "Bahasa Indonesia" }
}

/// In-code string tables so the language can switch at runtime without
/// relaunching (an app bundle's .lproj lookup follows the system language).
public enum Strings {
    public static func text(_ key: String, _ language: Language) -> String {
        let table = language == .id ? id : en
        return table[key] ?? en[key] ?? key
    }

